#!/usr/bin/env python3
"""
race_test.py — the concurrency test your order-placement mechanism must pass.

Run exactly as shipped. Do not edit this file.

--------------------------------------------------------------------------------
THE CONTRACT
--------------------------------------------------------------------------------
This test calls one database function. You build it. Its signature and behaviour
are fixed, because Kloud Kart's application has to call it and this test stands
in for the application:

    place_order(
        p_customer_id  bigint,
        p_product_id   bigint,
        p_quantity     integer
    ) RETURNS TABLE (
        success   boolean,
        order_id  bigint,
        message   text
    )

Required behaviour:

  * On success            -> success = true,  order_id = the new order's id,
                            message anything you like.
  * On insufficient stock -> success = false, order_id = NULL, and message
                            containing the words "out of stock"
                            (case-insensitive). Nana promised the customer an
                            instant, clear "out of stock", so the caller must be
                            able to tell this case from a crash.
  * It must never raise an unhandled exception under contention. A serialization
    failure that reaches the client is a failure of this test: retry inside the
    function, or choose a strategy that does not produce one.
  * It must never leave stock_quantity below zero.
  * It must decrement stock and create the order in the same unit of work: no
    order without its stock movement, no stock movement without its order.
  * It must write the movement to inventory_log. Nana asked for a trail an
    auditor could walk through, and that includes sales placed under contention.
  * How many rows it writes to orders / order_items / inventory_log is your
    design decision; the test only checks that exactly one order exists per
    successful call.

Locking strategy, isolation level, and whether you use a constraint, a trigger,
a procedure or all three are yours. The test does not care how.

--------------------------------------------------------------------------------
WHAT IT TESTS
--------------------------------------------------------------------------------
  Test 1  Two buyers, one unit.   Two calls fired at the same moment for the
                                  last unit: exactly one succeeds, the other is
                                  told out of stock. Repeated 25 times.

  Test 2  Flash sale.             400 concurrent attempts on a product with 50
                                  units. Exactly 50 succeed.

  Test 3  Oversell attempt.       One call for more units than exist. Refused
                                  cleanly, stock untouched.

  Test 4  Trail intact.           Every successful purchase left a stock
                                  movement behind.

--------------------------------------------------------------------------------
USAGE
--------------------------------------------------------------------------------
    pip install psycopg2-binary
    export DATABASE_URL=postgresql://user:pass@localhost:5432/kloudkart
    python race_test.py                 # all tests
    python race_test.py --test 1        # one test
    python race_test.py --verbose       # show every call's result

The test creates its own products (named 'RACE TEST FIXTURE ...'), uses an
existing customer, and removes its own fixtures afterwards.
"""

from __future__ import annotations

import argparse
import os
import sys
import threading
import time
from dataclasses import dataclass, field

try:
    import psycopg2
    import psycopg2.extras
except ImportError:
    sys.exit("psycopg2 is not installed. Run: pip install psycopg2-binary")

FIXTURE_PREFIX = "RACE TEST FIXTURE"
DSN = os.environ.get("DATABASE_URL")

TEST1_ROUNDS = 25
TEST2_BUYERS = 400
TEST2_STOCK = 50


# ----------------------------------------------------------------- plumbing
def connect():
    return psycopg2.connect(DSN)


@dataclass
class CallResult:
    success: bool | None = None
    order_id: int | None = None
    message: str = ""
    error: str = ""
    elapsed: float = 0.0


def call_place_order(customer_id: int, product_id: int, quantity: int,
                     barrier: threading.Barrier | None,
                     out: CallResult) -> None:
    """One buyer. Opens its own connection, waits at the barrier, then fires."""
    conn = None
    try:
        conn = connect()
        conn.autocommit = True
        cur = conn.cursor()
        if barrier is not None:
            barrier.wait(timeout=60)
        t0 = time.perf_counter()
        cur.execute(
            "SELECT success, order_id, message FROM place_order(%s, %s, %s)",
            (customer_id, product_id, quantity),
        )
        row = cur.fetchone()
        out.elapsed = time.perf_counter() - t0
        if row is None:
            out.error = "place_order returned no row"
        else:
            out.success, out.order_id, out.message = row[0], row[1], row[2] or ""
    except Exception as exc:                                  # noqa: BLE001
        out.error = f"{type(exc).__name__}: {exc}".strip()
    finally:
        if conn is not None:
            try:
                conn.close()
            except Exception:                                 # noqa: BLE001
                pass


def fire(customer_id: int, product_id: int, quantity: int,
         n: int) -> list[CallResult]:
    """Fire n concurrent calls, released together by a barrier."""
    barrier = threading.Barrier(n)
    results = [CallResult() for _ in range(n)]
    threads = [
        threading.Thread(
            target=call_place_order,
            args=(customer_id, product_id, quantity, barrier, results[i]),
            daemon=True,
        )
        for i in range(n)
    ]
    for t in threads:
        t.start()
    for t in threads:
        t.join(timeout=120)
    return results


# ----------------------------------------------------------------- fixtures
def preflight() -> tuple[int, int]:
    """Check the contract is satisfiable before testing it. Returns
    (customer_id, next_product_id)."""
    with connect() as conn, conn.cursor() as cur:
        cur.execute("""
            SELECT p.proname, pg_get_function_identity_arguments(p.oid)
            FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
            WHERE p.proname = 'place_order' AND n.nspname NOT IN ('pg_catalog','information_schema')
        """)
        found = cur.fetchall()
        if not found:
            fail("No function named place_order exists in this database.\n"
                 "        The contract is documented at the top of this file.")
        cur.execute("SELECT min(customer_id) FROM customers")
        row = cur.fetchone()
        if not row or row[0] is None:
            fail("The customers table is empty. Load the data bundle first.")
        customer_id = row[0]
        cur.execute("SELECT coalesce(max(product_id), 0) + 1000 FROM products")
        next_pid = cur.fetchone()[0]
    print(f"  place_order found: {found[0][0]}({found[0][1]})")
    return customer_id, next_pid


def make_fixture(product_id: int, stock: int, label: str) -> None:
    with connect() as conn, conn.cursor() as cur:
        cur.execute("DELETE FROM products WHERE product_id = %s", (product_id,))
        cur.execute(
            "INSERT INTO products (product_id, product_name, category_id, price,"
            " stock_quantity, created_at) VALUES (%s, %s, NULL, 100.00, %s, now())",
            (product_id, f"{FIXTURE_PREFIX} {label}", stock),
        )
        conn.commit()


def stock_of(product_id: int) -> int | None:
    with connect() as conn, conn.cursor() as cur:
        cur.execute("SELECT stock_quantity FROM products WHERE product_id = %s",
                    (product_id,))
        row = cur.fetchone()
        return row[0] if row else None


def orders_for(product_id: int) -> int:
    """Distinct orders that contain this product."""
    with connect() as conn, conn.cursor() as cur:
        cur.execute("SELECT count(DISTINCT order_id) FROM order_items "
                    "WHERE product_id = %s", (product_id,))
        return cur.fetchone()[0]


def log_rows_for(product_id: int) -> int:
    with connect() as conn, conn.cursor() as cur:
        cur.execute("SELECT count(*) FROM inventory_log WHERE product_id = %s",
                    (product_id,))
        return cur.fetchone()[0]


def cleanup() -> None:
    with connect() as conn, conn.cursor() as cur:
        cur.execute(f"SELECT product_id FROM products "
                    f"WHERE product_name LIKE '{FIXTURE_PREFIX}%%'")
        pids = [r[0] for r in cur.fetchall()]
        if pids:
            cur.execute("SELECT DISTINCT order_id FROM order_items "
                        "WHERE product_id = ANY(%s)", (pids,))
            oids = [r[0] for r in cur.fetchall()]
            cur.execute("DELETE FROM order_items WHERE product_id = ANY(%s)", (pids,))
            if oids:
                cur.execute("DELETE FROM order_items WHERE order_id = ANY(%s)", (oids,))
                cur.execute("DELETE FROM orders WHERE order_id = ANY(%s)", (oids,))
            cur.execute("DELETE FROM inventory_log WHERE product_id = ANY(%s)", (pids,))
            cur.execute("DELETE FROM products WHERE product_id = ANY(%s)", (pids,))
        conn.commit()


# ----------------------------------------------------------------- reporting
FAILURES: list[str] = []


def fail(msg: str) -> None:
    print(f"  FAIL  {msg}")
    FAILURES.append(msg)


def ok(msg: str) -> None:
    print(f"  ok    {msg}")


def describe(results: list[CallResult], verbose: bool) -> None:
    if not verbose:
        return
    for i, r in enumerate(results):
        print(f"        [{i:>3}] success={r.success} order_id={r.order_id} "
              f"{r.elapsed*1000:7.1f}ms msg={r.message!r} err={r.error!r}")


def out_of_stock(r: CallResult) -> bool:
    return "out of stock" in (r.message or "").lower()


# ----------------------------------------------------------------- the tests
def test1(customer_id: int, base_pid: int, verbose: bool) -> None:
    print(f"\nTest 1 — two buyers, one unit, {TEST1_ROUNDS} rounds")
    bad_rounds = []
    for rnd in range(TEST1_ROUNDS):
        pid = base_pid + rnd
        make_fixture(pid, 1, f"T1 r{rnd}")
        results = fire(customer_id, pid, 1, 2)
        wins = [r for r in results if r.success is True]
        errs = [r for r in results if r.error]
        refusals = [r for r in results if r.success is False]
        final = stock_of(pid)
        orders = orders_for(pid)

        problems = []
        if errs:
            problems.append("unhandled error: " + "; ".join(e.error for e in errs))
        if len(wins) != 1:
            problems.append(f"{len(wins)} calls succeeded, expected exactly 1")
        if len(refusals) != 1:
            problems.append(f"{len(refusals)} calls were refused, expected exactly 1")
        elif not out_of_stock(refusals[0]):
            problems.append(f"refusal message does not say 'out of stock': "
                            f"{refusals[0].message!r}")
        if final != 0:
            problems.append(f"stock ended at {final}, expected 0")
        if orders != 1:
            problems.append(f"{orders} orders contain the product, expected 1")
        if problems:
            bad_rounds.append((rnd, problems))
            describe(results, True)
        else:
            describe(results, verbose)

    if bad_rounds:
        for rnd, problems in bad_rounds[:5]:
            for p in problems:
                fail(f"round {rnd}: {p}")
        fail(f"{len(bad_rounds)}/{TEST1_ROUNDS} rounds failed. "
             f"A race that fails sometimes is the race Nana already has.")
    else:
        ok(f"{TEST1_ROUNDS}/{TEST1_ROUNDS} rounds: exactly one winner, "
           f"stock 0, one order, no errors")


def test2(customer_id: int, pid: int, verbose: bool) -> None:
    print(f"\nTest 2 — flash sale: {TEST2_BUYERS} buyers, {TEST2_STOCK} units")
    make_fixture(pid, TEST2_STOCK, "T2 flash")
    t0 = time.perf_counter()
    results = fire(customer_id, pid, 1, TEST2_BUYERS)
    wall = time.perf_counter() - t0
    describe(results, verbose)

    wins = [r for r in results if r.success is True]
    errs = [r for r in results if r.error]
    refusals = [r for r in results if r.success is False]
    final = stock_of(pid)
    orders = orders_for(pid)
    print(f"        {len(wins)} sold, {len(refusals)} refused, {len(errs)} errored, "
          f"wall clock {wall:.2f}s")

    if errs:
        shown = {}
        for e in errs:
            shown[e.error.split("\n")[0][:120]] = shown.get(e.error.split("\n")[0][:120], 0) + 1
        for msg, n in list(shown.items())[:5]:
            fail(f"{n} calls raised: {msg}")
    if len(wins) != TEST2_STOCK:
        fail(f"{len(wins)} calls succeeded, expected exactly {TEST2_STOCK}")
    if final != 0:
        fail(f"stock ended at {final}, expected 0"
             + ("  <-- oversold" if final is not None and final < 0 else ""))
    if orders != len(wins):
        fail(f"{orders} orders contain the product but {len(wins)} calls "
             f"reported success")
    bad_msg = [r for r in refusals if not out_of_stock(r)]
    if bad_msg:
        fail(f"{len(bad_msg)} refusals did not say 'out of stock', "
             f"e.g. {bad_msg[0].message!r}")
    if not FAILURES:
        ok(f"exactly {TEST2_STOCK} sold, none oversold, no errors, {wall:.2f}s")
    if wall > 10:
        print(f"        note: {wall:.1f}s for {TEST2_BUYERS} attempts.")


def test3(customer_id: int, pid: int, verbose: bool) -> None:
    print("\nTest 3 — asking for more than exists")
    make_fixture(pid, 3, "T3 oversell")
    results = fire(customer_id, pid, 10, 1)
    describe(results, verbose)
    r = results[0]
    if r.error:
        fail(f"raised instead of refusing: {r.error}")
    elif r.success is not False:
        fail(f"success={r.success}, expected False for a 10-unit order against 3 units")
    elif not out_of_stock(r):
        fail(f"refusal message does not say 'out of stock': {r.message!r}")
    final = stock_of(pid)
    if final != 3:
        fail(f"stock changed to {final} on a refused order, expected 3")
    if not any(f for f in FAILURES if "Test 3" in f) and r.success is False and final == 3:
        ok("refused cleanly, stock untouched")


def test4(customer_id: int, pid: int, verbose: bool) -> None:
    print("\nTest 4 — audit trail after contention")
    make_fixture(pid, 5, "T4 trail")
    results = fire(customer_id, pid, 1, 12)
    describe(results, verbose)
    wins = sum(1 for r in results if r.success is True)
    logged = log_rows_for(pid)
    if wins == 0:
        fail("no call succeeded, so the trail cannot be checked")
        return
    if logged < wins:
        fail(f"{wins} units sold but only {logged} rows in inventory_log. "
             f"Nana asked for a trail an auditor could walk through")
    else:
        ok(f"{wins} sold, {logged} movements recorded")


# ----------------------------------------------------------------- main
def main() -> int:
    ap = argparse.ArgumentParser(
        description="Concurrency test for Kloud Kart's order-placement mechanism.")
    ap.add_argument("--test", type=int, choices=[1, 2, 3, 4], action="append",
                    help="run only these tests (repeatable)")
    ap.add_argument("--verbose", action="store_true", help="print every call")
    ap.add_argument("--keep-fixtures", action="store_true",
                    help="leave fixture rows behind for inspection")
    args = ap.parse_args()

    if not DSN:
        print("DATABASE_URL is not set.\n"
              "  export DATABASE_URL=postgresql://user:pass@localhost:5432/kloudkart",
              file=sys.stderr)
        return 2

    print("race_test.py — Kloud Kart order placement under contention")
    print("=" * 66)
    try:
        customer_id, base_pid = preflight()
    except psycopg2.Error as exc:
        print(f"  cannot connect or query: {exc}", file=sys.stderr)
        return 2

    cleanup()
    chosen = set(args.test or [1, 2, 3, 4])
    try:
        if 1 in chosen:
            test1(customer_id, base_pid, args.verbose)
        if 2 in chosen:
            test2(customer_id, base_pid + 100, args.verbose)
        if 3 in chosen:
            test3(customer_id, base_pid + 200, args.verbose)
        if 4 in chosen:
            test4(customer_id, base_pid + 300, args.verbose)
    finally:
        if not args.keep_fixtures:
            try:
                cleanup()
            except Exception as exc:                          # noqa: BLE001
                print(f"  (fixture cleanup failed: {exc})", file=sys.stderr)

    print("\n" + "=" * 66)
    if FAILURES:
        print(f"FAILED — {len(FAILURES)} problem(s):")
        for f in FAILURES:
            print(f"  - {f}")
        return 1
    print("PASSED — exactly one buyer gets the last unit, every time.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
